// Mkpow10 writes c/pow10.c, the powers of ten the runtime formats floats
// with: 10^q for q from -348 to 347, each as the 128 bits of its
// mantissa below the leading one's place, rounded down, the table Go's
// strconv calls detailedPowersOfTen and computes the same way. Ryū's
// shortest formatting multiplies by them, as Go's does.
//
//	go run mkpow10.go
//	go run mkpow10.go -o /tmp/pow10.c
package main

import (
	"bytes"
	"flag"
	"fmt"
	"log"
	"math/big"
	"os"
)

const (
	minExp10 = -348
	maxExp10 = 347
)

func main() {
	out := flag.String("o", "c/pow10.c", "the file to write")
	flag.Parse()
	var b bytes.Buffer
	b.WriteString(`// Copyright 2026 The Snello Programming Language. All rights reserved.
// Use of this source code is governed by a BSD-style
// license that can be found in the LICENSE file.

// Code generated by mkpow10.go; DO NOT EDIT.

#include <stdint.h>

// sn_pow10[q+348] is 10^q's mantissa in 128 bits, the low word first,
// rounded down, its top bit set: Go's detailedPowersOfTen.
const uint64_t sn_pow10[696][2] = {
`)
	mask := new(big.Int).Sub(new(big.Int).Lsh(big.NewInt(1), 64), big.NewInt(1))
	for q := minExp10; q <= maxExp10; q++ {
		m := mantissa(q)
		lo := new(big.Int).And(m, mask).Uint64()
		hi := new(big.Int).Rsh(m, 64).Uint64()
		fmt.Fprintf(&b, "    {0x%016X, 0x%016X}, // 1e%d\n", lo, hi, q)
	}

	b.WriteString("};\n")
	if err := os.WriteFile(*out, b.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}

// mantissa returns the 128 bits of 10^q from its leading one, rounded
// down: 10^q times or over the power of two that puts its top bit at
// bit 127.
func mantissa(q int) *big.Int {
	ten := new(big.Int).Exp(big.NewInt(10), big.NewInt(int64(abs(q))), nil)
	if q >= 0 {
		if n := ten.BitLen(); n > 128 {
			return ten.Rsh(ten, uint(n-128))
		} else {
			return ten.Lsh(ten, uint(128-n))
		}
	}

	k := uint(127 + ten.BitLen())
	m := new(big.Int).Quo(new(big.Int).Lsh(big.NewInt(1), k), ten)
	for m.BitLen() > 128 {
		k--
		m.Quo(new(big.Int).Lsh(big.NewInt(1), k), ten)
	}

	for m.BitLen() < 128 {
		k++
		m.Quo(new(big.Int).Lsh(big.NewInt(1), k), ten)
	}

	return m
}

func abs(x int) int {
	if x < 0 {
		return -x
	}

	return x
}
